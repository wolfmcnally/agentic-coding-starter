from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture
def caller_repo(tmp_path: Path) -> Path:
    root = tmp_path / "repo"
    (root / "bin").mkdir(parents=True)
    shutil.copy2(
        REPO_ROOT / "bin" / "check-toolchain-callers",
        root / "bin" / "check-toolchain-callers",
    )
    return root


def _run(root: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            sys.executable,
            str(root / "bin" / "check-toolchain-callers"),
            "--root",
            str(root),
        ],
        text=True,
        capture_output=True,
        check=False,
    )


def test_repository_runtime_callers_pass(caller_repo: Path) -> None:
    (caller_repo / "bin" / "workflow").write_text(
        '#!/usr/bin/env bash\n./bin/python bin/task\nPYTHON="$(./bin/python -c '
        "'import sys; print(sys.executable)')\"\n"
    )

    result = _run(caller_repo)

    assert result.returncode == 0, result.stdout


@pytest.mark.parametrize(
    ("relative", "line"),
    [
        ("bin/workflow", "python3 bin/task\n"),
        ("policies/procedure.md", "python tests/tool.py\n"),
        ("plan/phase.md", "output | python3 -c 'print(1)'\n"),
        ("proposals/open-change.md", "python3 bin/task\n"),
        ("web/vite.config.js", "python3 web/scripts/generate.py\n"),
    ],
)
def test_ambient_or_versioned_operational_callers_fail(
    caller_repo: Path, relative: str, line: str
) -> None:
    path = caller_repo / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(line)

    result = _run(caller_repo)

    assert result.returncode == 1
    assert f"{relative}:1:" in result.stdout


def test_briefs_are_not_an_executed_surface(caller_repo: Path) -> None:
    """A brief may quote the defect it reports without failing the gate.

    The checker's regex cannot tell "run `python3 bin/task`" — an instruction —
    from "the shebang resolved to the ambient interpreter, which was 3.10" — a
    description of a defect. While the delegated-invocation recipes lived in a
    brief, scanning briefs was correct and this tension was unresolvable: a
    defect report failed the gate twice while documenting the defect. The
    recipes are now generated by `bin/kickoff-config watch`, so a brief executes
    nothing and the scan narrows to what runs.
    """
    brief = caller_repo / "briefs" / "defect-report.md"
    brief.parent.mkdir(parents=True, exist_ok=True)
    brief.write_text(
        "The shebang resolved to the ambient `python3`, which was 3.10.12.\n"
        "Reproduced with `python3 bin/task` on the affected host.\n"
    )

    result = _run(caller_repo)

    assert result.returncode == 0, result.stdout


def test_external_runtime_literals_and_python_shebangs_are_allowed(
    caller_repo: Path,
) -> None:
    (caller_repo / "bin" / "script").write_text("#!/usr/bin/env python3\n")
    (caller_repo / "bin" / "aws-setup").write_text("--runtime python3.12 \\\n")
    dockerfile = caller_repo / "infra" / "lambda" / "Dockerfile"
    dockerfile.parent.mkdir(parents=True)
    dockerfile.write_text("RUN python -m pip install package\n")

    result = _run(caller_repo)

    assert result.returncode == 0, result.stdout
